async function migrateFromSync() {
  const localData = await chrome.storage.local.get('chats');
  if (localData.chats) return;
  const keys = ['chats', 'columns', 'sidebarChat', 'theme', 'prompts', 'locale'];
  const syncData = await chrome.storage.sync.get(keys);
  const toSet = {};
  for (const k of keys) {
    if (syncData[k] !== undefined) toSet[k] = syncData[k];
  }
  if (Object.keys(toSet).length > 0) {
    await chrome.storage.local.set(toSet);
  }
}

async function updateChatScripts() {
  const chats = await store.get('chats') || [];
  const targets = chats.filter(c => c.enabled && c.inject);
  try { await chrome.scripting.unregisterContentScripts({ ids: ['aichats-content'] }); } catch {}
  if (targets.length === 0) return;
  const matches = targets.map(c => {
    const url = c.url.endsWith('/') ? c.url : c.url + '/';
    return url + '*';
  });
  try {
    await chrome.scripting.registerContentScripts([{
      id: 'aichats-content',
      js: ['content.js'],
      matches,
      runAt: 'document_idle',
      allFrames: true,
    }]);
  } catch (e) { console.error('registerContentScripts error:', e); }
}

async function prefetchIcons() {
  const chats = await store.get('chats');
  if (!Array.isArray(chats)) return;
  const reqInit = { signal: AbortSignal.timeout(3000) };
  let changed = false;
  await Promise.all(chats.map(async (chat) => {
    let newIcon = '';
    try {
      newIcon = await autoDetectFavicon(chat.url);
    } catch {}
    if (!newIcon) {
      const hostname = new URL(chat.url).hostname;
      const googleUrl = `https://www.google.com/s2/favicons?domain=${hostname}&sz=32`;
      try {
        const r = await fetch(googleUrl, reqInit);
        if (r.ok) {
          const ct = r.headers.get('Content-Type') || '';
          if (!ct.startsWith('text/')) { newIcon = googleUrl; }
          r.body?.cancel();
        }
      } catch {}
    }
    if (newIcon !== chat.icon) {
      chat.icon = newIcon;
      changed = true;
    }
  }));
  if (changed) await store.set('chats', chats);
}

